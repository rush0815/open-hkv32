# PlatformIO pre-build script: embeds src/net/web/index.html gzip-compressed
# into src/net/web_index.h (delivered compressed, the browser unpacks it).
import gzip
import os

try:
    Import("env")  # noqa: F821 (provided by SCons)
    root = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

src = os.path.join(root, "src", "net", "web", "index.html")
dst = os.path.join(root, "src", "net", "web_index.h")

with open(src, "rb") as f:
    raw = f.read()
data = gzip.compress(raw, compresslevel=9, mtime=0)

lines = ["// Generated by tools/embed_web.py from src/net/web/index.html - do not edit.",
         "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "",
         "static const uint8_t kWebIndexGz[] = {"]
for i in range(0, len(data), 20):
    lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
lines += ["};", "static const size_t kWebIndexGzLen = sizeof(kWebIndexGz);", ""]
out = "\n".join(lines)

old = open(dst).read() if os.path.exists(dst) else ""
if old != out:
    with open(dst, "w") as f:
        f.write(out)
    print("embed_web: %s (%d -> %d bytes gzip)" % (os.path.relpath(dst, root), len(raw), len(data)))
